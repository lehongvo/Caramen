#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gcd_for_several_types() {
        assert_eq!(gcd(48_u32, 18), 6);
        assert_eq!(gcd(0_u8, 7), 7);
        assert_eq!(gcd(0_i64, 0), 0);
        assert_eq!(gcd(u64::MAX, 3), 3);
        assert_eq!(gcd(1_071_i32, 462), 21);
    }

    #[test]
    fn checked_sums() {
        assert_eq!(checked_sum(&[200_u8, 55]), Some(255));
        assert_eq!(checked_sum(&[200_u8, 56]), None);
        assert_eq!(checked_sum::<i32>(&[]), Some(0));
        assert_eq!(checked_sum(&[i64::MAX, -1, 1]), Some(i64::MAX));
        assert_eq!(checked_sum(&[i64::MAX, 1, -1]), None);
    }

    #[test]
    fn factorials_overflow_at_the_right_place() {
        assert_eq!(
            checked_factorial::<u64>(20),
            Some(2_432_902_008_176_640_000)
        );
        assert_eq!(checked_factorial::<u64>(21), None);
        assert_eq!(checked_factorial::<u8>(5), Some(120));
        assert_eq!(checked_factorial::<u8>(6), None);
        assert_eq!(checked_factorial::<u32>(0), Some(1));
        assert_eq!(checked_factorial::<u32>(1), Some(1));
        assert_eq!(checked_factorial::<u8>(300), None);
    }

    #[test]
    fn digits() {
        assert_eq!(decimal_digits(9_042_u16), vec![9, 0, 4, 2]);
        assert_eq!(decimal_digits(0_u32), vec![0]);
        assert_eq!(decimal_digits(u64::MAX).len(), 20);
        assert_eq!(decimal_digits(i32::MAX), vec![2, 1, 4, 7, 4, 8, 3, 6, 4, 7]);
        assert_eq!(decimal_digits(<u8 as Integer>::MAX), vec![2, 5, 5]);
    }
}
