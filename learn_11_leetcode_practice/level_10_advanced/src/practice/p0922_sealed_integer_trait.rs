//! # Problem 0922: A Sealed `Integer` Trait
//!
//! - **Difficulty:** Medium
//! - **Topics:** sealed traits, associated constants, implementing a trait for many types with a macro, generic numeric algorithms, `try_fold`
//! - **Source:** Original · [Reference: Traits](https://doc.rust-lang.org/reference/items/traits.html) · [Reference: Associated constants](https://doc.rust-lang.org/reference/items/associated-items.html#associated-constants)
//!
//! ## Problem
//!
//! A library wants generic functions over "the built-in integer types", but it does not want users to
//! implement its trait for their own types (that would let the library never add a method without
//! breaking them). The **sealed trait** pattern does that: the trait has a supertrait that lives in
//! a private module, so code outside this module can use the trait but never implement it.
//!
//! The trait and its implementations for `u8`, `u16`, `u32`, `u64`, `i32` and `i64` are given
//! (generated by a small macro):
//!
//! ```text
//! pub trait Integer: private::Sealed + Copy + PartialEq + PartialOrd + Debug {
//!     const ZERO: Self; const ONE: Self; const TEN: Self; const MAX: Self;
//!     fn checked_add(self, other: Self) -> Option<Self>;
//!     fn checked_mul(self, other: Self) -> Option<Self>;
//!     fn rem(self, other: Self) -> Self;
//!     fn div(self, other: Self) -> Self;
//!     fn to_u8(self) -> u8;            // only for values 0..=9 in this problem
//! }
//! ```
//!
//! Implement four generic functions using **only** the trait's items:
//!
//! - `gcd<T: Integer>(a: T, b: T) -> T` for non-negative `a`, `b` (`gcd(0, 0) == 0`).
//! - `checked_sum<T: Integer>(values: &[T]) -> Option<T>`: `None` on overflow.
//! - `checked_factorial<T: Integer>(n: u32) -> Option<T>`: `n!` in type `T`, `None` if it overflows.
//! - `decimal_digits<T: Integer>(value: T) -> Vec<u8>`: the decimal digits of a non-negative value,
//!   most significant first (`[0]` for zero).
//!
//! ## Examples
//!
//! ```text
//! gcd(48_u32, 18)                  => 6
//! checked_sum(&[200_u8, 55])       => Some(255)
//! checked_sum(&[200_u8, 56])       => None
//! checked_factorial::<u64>(20)     => Some(2_432_902_008_176_640_000)
//! checked_factorial::<u64>(21)     => None
//! decimal_digits(9_042_u16)        => [9, 0, 4, 2]
//! ```
//!
//! ## Constraints
//!
//! - Inputs of `gcd` and `decimal_digits` are non-negative.
//!
//! ## Hints
//!
//! 1. Write `T::ZERO`, `T::ONE`, `T::TEN` for the constants; `a.rem(b)` for `a % b`.
//! 2. `values.iter().try_fold(T::ZERO, |acc, &v| acc.checked_add(v))` stops at the first `None`.
//! 3. For the factorial you need the numbers `1, 2, ..., n` **as `T`**: build them by adding `T::ONE`
//!    step by step (with `checked_add`, since `n` itself may not fit in `T`).

use std::fmt::Debug;

mod private {
    pub trait Sealed {}
}

pub trait Integer: private::Sealed + Copy + PartialEq + PartialOrd + Debug {
    const ZERO: Self;
    const ONE: Self;
    const TEN: Self;
    const MAX: Self;
    fn checked_add(self, other: Self) -> Option<Self>;
    fn checked_mul(self, other: Self) -> Option<Self>;
    fn rem(self, other: Self) -> Self;
    fn div(self, other: Self) -> Self;
    fn to_u8(self) -> u8;
}

macro_rules! impl_integer {
    ($($t:ty),* $(,)?) => {
        $(
            impl private::Sealed for $t {}

            impl Integer for $t {
                const ZERO: Self = 0;
                const ONE: Self = 1;
                const TEN: Self = 10;
                const MAX: Self = <$t>::MAX;

                fn checked_add(self, other: Self) -> Option<Self> {
                    <$t>::checked_add(self, other)
                }

                fn checked_mul(self, other: Self) -> Option<Self> {
                    <$t>::checked_mul(self, other)
                }

                fn rem(self, other: Self) -> Self {
                    self % other
                }

                fn div(self, other: Self) -> Self {
                    self / other
                }

                fn to_u8(self) -> u8 {
                    // Only called with a single decimal digit (0..=9).
                    self as u8
                }
            }
        )*
    };
}

